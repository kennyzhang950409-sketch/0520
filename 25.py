import pandas as pd

# ==========================================
# 0. 建立範例資料並儲存（方便您直接執行測試）
# ==========================================
sample_data = {
    '商品名稱': ['蘋果', '香蕉', '橘子', '葡萄', '西瓜'],
    '單價': [30, 15, 25, 80, 120],
    '庫存數量': [100, 150, 80, 50, 30],
    '銷售數量': [80, 120, 60, 45, 25]
}
# 轉成 DataFrame 並存成 CSV 檔
df_sample = pd.DataFrame(sample_data)
df_sample.to_csv('product_data.csv', index=False, encoding='utf-8-sig')


# ==========================================
# 1. 讀取檔案
# ==========================================
# 如果您的檔案是 Excel 檔 (.xlsx)，請改用：df = pd.read_excel('您的檔案名稱.xlsx')
file_name = 'product_data.csv'
df = pd.read_csv(file_name, encoding='utf-8-sig')

print("--- 原始資料內容 ---")
print(df)
print("\n" + "="*50 + "\n")


# ==========================================
# (1) 計算每個商品的總庫存價值
# 數學公式：總庫存價值 = 單價 × 庫存數量
# ==========================================
df['總庫存價值'] = df['單價'] * df['庫存數量']

print("(1) 每個商品的總庫存價值：")
print(df[['商品名稱', '總庫存價值']])
print("\n" + "="*50 + "\n")


# ==========================================
# (2) 找出最暢銷的商品（以銷售數量最多為基準）
# ==========================================
# idxmax() 可以找出「銷售數量」最大值所在的索引（列位置）
best_seller_index = df['銷售數量'].idxmax()
best_seller = df.loc[best_seller_index]

print(f"(2) 最暢銷的商品是：【{best_seller['商品名稱']}】")
print(f"    銷售數量為：{best_seller['銷售數量']} 件")
print("\n" + "="*50 + "\n")


# ==========================================
# (3) 計算 9 折後的收入
# 數學公式：總收入 = ∑(單價 × 銷售數量) × 0.9
# ==========================================
# 先計算每個商品的原始銷售收入，再加總
total_original_revenue = (df['單價'] * df['銷售數量']).sum()
# 打 9 折
discounted_revenue = total_original_revenue * 0.9

print(f"(3) 收入計算結果：")
print(f"    原始總收入：${total_original_revenue:,.0f}")
print(f"    打 9 折後的總收入：${discounted_revenue:,.0f}")