import pandas as pd

# -----------------------------
# 使用字典建立 DataFrame
# -----------------------------
data_dict = {
    "Product": ["Apple", "Banana", "Orange", "Mango", "Grape", "Guava"],
    "Price": [30, 20, 25, 60, 45, 35],
    "Sales": [100, 150, 80, 60, 90, 54]
}

df1 = pd.DataFrame(data_dict)

print("【使用字典建立 DataFrame】")
print(df1)

# -----------------------------
# 使用列表(子列表)建立 DataFrame
# -----------------------------
data_list = [
    ["Apple", 30, 100],
    ["Banana", 20, 150],
    ["Orange", 25, 80],
    ["Mango", 60, 60],
    ["Grape", 45, 90],
    ["Guava", 35, 54]
]

df2 = pd.DataFrame(data_list, columns=["Product", "Price", "Sales"])

print("\n【使用列表建立 DataFrame】")
print(df2)

# -----------------------------
# 顯示前5筆資料
# -----------------------------
print("\n【前5筆資料】")
print(df2.head())

# -----------------------------
# 顯示後5筆資料
# -----------------------------
print("\n【後5筆資料】")
print(df2.tail())

# -----------------------------
# 顯示資料列數與欄數
# -----------------------------
print("\n【資料列數與欄數】")
print(df2.shape)

# -----------------------------
# 顯示欄位名稱
# -----------------------------
print("\n【欄位名稱】")
print(df2.columns)

# -----------------------------
# 顯示資料型態
# -----------------------------
print("\n【資料型態】")
print(df2.dtypes)

# -----------------------------
# 顯示非空值數量
# -----------------------------
print("\n【非空值數量】")
print(df2.count())

# -----------------------------
# 計算統計資訊
# -----------------------------
print("\n【統計資訊】")

stats = df2.describe().round(2)

print(stats)

# -----------------------------
# 儲存統計資訊為 CSV
# -----------------------------
stats.to_csv("0520_stock2.csv")

print("\n統計資訊已存成 0520_stock2.csv")